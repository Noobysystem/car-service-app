scale = 2.0
mat = fitz.Matrix(scale, scale)

for name, page_num in exact_pages.items():
    if page_num > len(doc):
        continue
    page = doc[page_num - 1]
    pix = page.get_pixmap(matrix=mat)
    img = Image.frombytes("RGB", [pix.width, pix.height], pix.samples)
    draw = ImageDraw.Draw(img)
    
    # Находим японский текст по координатам и наносим русский перевод
    text_data = page.get_text("dict")
    for block in text_data.get("blocks", []):
        for line in block.get("lines", []):
            line_text = "".join(span.get("text", "") for span in line.get("spans", [])).strip()
            bbox = line.get("bbox")
            for jp, ru in TRANSLATIONS.items():
                if jp in line_text:
                    x0, y0, x1, y1 = bbox
                    pad_x, pad_y = 4, 2
                    # Белая плашка с мягкой рамкой для читаемости
                    draw.rectangle(
                        [x0*scale - pad_x, y0*scale - pad_y, x1*scale + pad_x, y1*scale + pad_y],
                        fill="white", outline="#94a3b8", width=1
                    )
                    f_size = max(11, int((y1 - y0) * scale * 0.85))
                    font = get_font(f_size)
                    draw.text((x0*scale - 1, y0*scale - 1), ru, fill="#0f172a", font=font)
                    break

    out_path = os.path.join(output_dir, f"{name}.png")
    img.save(out_path, quality=95)
    print(f"Готово: {name}.png (стр. {page_num})")

doc.close()
print("Все схемы успешно русифицированы!")
